"""LangGraph state definition for the DYTM verification loop.

The ``DYTMState`` TypedDict is the single source of truth that flows through
every node in the LangGraph ``StateGraph``.  Each node reads from and writes
to this dict; LangGraph handles persistence and checkpointing automatically.
"""

from __future__ import annotations

from typing import Literal, Optional
from typing_extensions import TypedDict


class DYTMState(TypedDict, total=False):
    """State that flows through the DYTM LangGraph pipeline.

    Attributes:
        prompt: The Executive's original natural-language request.
        code: Python source code generated by the Operator.
        pbt_payload: Validated PBT JSON payload (dict form of ``PBTPayload``).
        cnl_text: Controlled Natural Language contract rendered by the
                  Translator.
        approved: Whether the Executive approved the CNL contract.
        test_result: Outcome of the Doer's Hypothesis test run
                     (``"pass"``, ``"fail"``, or ``"error"``).
        retry_count: How many times the Operator has retried so far.
        max_retries: Upper bound on retries before the loop gives up.
        counterexample: Minimal failing input found by Hypothesis (if any).
        error_trace: Stderr / traceback from the most recent test failure.
        mode: Operating mode — ``"eval"`` for benchmark auto-approve,
              ``"free"`` for interactive human-in-the-loop.
        security_passed: Whether the ``ast``-based security scan approved
                         the generated code.
    """

    # -- Executive input ----------------------------------------------------
    prompt: str

    # -- Operator output ----------------------------------------------------
    code: str
    pbt_payload: dict  # serialised PBTPayload

    # -- Translator output --------------------------------------------------
    cnl_text: str

    # -- Approval gate ------------------------------------------------------
    approved: bool
    approval_feedback: Optional[str]  # Executive LLM reasoning or human feedback
    spec_retry_count: int  # how many times the contract was rejected & revised
    max_spec_retries: int  # upper bound on spec revision attempts

    # -- Doer output --------------------------------------------------------
    test_result: str  # "pass" | "fail" | "error"
    retry_count: int
    max_retries: int
    counterexample: Optional[str]
    error_trace: Optional[str]

    # -- Security scan ------------------------------------------------------
    security_passed: bool

    # -- Config -------------------------------------------------------------
    mode: Literal["eval", "free"]

    # -- Debug / diagnostics ------------------------------------------------
    _test_source: Optional[str]  # compiled test file content (for verbose output)
    _edge_only_fail: Optional[bool]  # True when PBT fails only on edge cases (soft pass)
    _prev_code: Optional[str]  # previous code attempt (for duplicate detection)
    _duplicate_code: Optional[bool]  # True when Coder generated same code as prev attempt
